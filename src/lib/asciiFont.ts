export function renderAsciiBanner(text: string): string {
  const upper = text.toUpperCase()
  const glyphs = [...upper].map((c) => GLYPHS[c] ?? GLYPHS[' '])
  const lines: string[] = []
  for (let row = 0; row < 5; row++) {
    lines.push(glyphs.map((g) => g[row]).join(' '))
  }
  return lines.join('\n')
}
